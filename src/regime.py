"""레짐(장세) 분류 — 50일선 기반 빠른 분류기.

구 프로젝트(soxl-soxs-bot)는 200일선을 썼다. 200일선은 둔감해서 급등장에서는 조정이 와도
계속 "상승"으로 잡힌다. 실제로 2025-09~2026-09 251거래일이 **전부 상승 한 구간**으로 분류돼,
2026년 7월 SOXX가 -21% 빠진 구간조차 상승으로 읽었다.

이 프로젝트는 **50일선 + 20일 기울기**를 쓴다. 같은 1년을 상승 174일 / 횡보 52일 / 하락 25일로
나눠 실제 장세를 따라간다. 대신 전환이 잦으므로(평균 지속 12일) 레짐 전환 자체가 주요 청산
트리거가 된다 — 익절·손절이 걸리기 전에 레짐이 먼저 바뀌는 경우가 많다.

⚠️ 200일선 대비 트레이드오프: 최근 국면(AI, 2023~)에서는 2배 가까이 앞서지만
   전체 15.7년으로 보면 뒤지고 낙폭도 크다. docs/STRATEGY.md 5장 참고.
"""
from __future__ import annotations

import pandas as pd

UP = "상승"
SIDEWAYS = "횡보"
DOWN = "하락"


def describe(close: pd.Series, days: int = 20, band: float = 0.06) -> pd.Series:
    """**표시 전용** 장세 라벨. 매매 판단에 쓰면 안 된다.

    `classify()` 는 거래를 위한 분류기라 일부러 둔하다. 50일선 기울기가 느리게 도는 덕에
    레짐이 안정적으로 유지되고, 그래서 포지션이 휩쏘로 찢기지 않는다. 대신 **사람 눈과
    어긋난다** — 2026년 7월은 SOXX가 -15.8% 빠졌는데 4~6월 급등이 50일 창에 남아 기울기가
    양수라 "하락"이 하루도 없었고, 반대로 9월은 +11.9% 올랐는데 12일이 "하락"이었다.

    이 함수는 그 어긋남을 사람이 확인할 수 있게 하려고 따로 둔다. 정의는 단순하다 —
    **최근 `days`일 가격 변화가 ±`band` 밖이면 상승/하락, 안이면 횡보**. 이동평균을 쓰지
    않아 후행이 없고, 2026년 5~9월에 대해 사용자가 의도한 라벨(5~6월 상승 / 7월 하락 /
    8~9월 횡보)과 78% 일치한다.

    ⚠️ **이 정의를 매매에 쓰지 마라.** 전환이 연 38회로 classify(25회)보다 훨씬 잦고,
    이 방향의 변형을 매매 레짐에 적용하면 최근 5년 성과가 29.04배 → 6.9~25배로 떨어진다.
    측정 내역은 docs/STRATEGY.md 6.6 에 있다. **라벨이 사람 눈에 맞는 것과 돈을 버는 것은
    다른 문제**이고, 이 저장소에서는 여러 번 후자가 이겼다.
    """
    chg = close.pct_change(days)
    out = pd.Series(SIDEWAYS, index=close.index, dtype=object)
    out[chg > band] = UP
    out[chg < -band] = DOWN
    out[chg.isna()] = None
    return out


def classify(close: pd.Series, ma_period: int = 50, slope_days: int = 20,
             price_days: int = 20) -> pd.Series:
    """일봉 종가로 레짐을 분류한다. **세 조건을 모두** 만족해야 상승/하락이다.

    - 상승: 종가가 이동평균 **위** + 이동평균이 **오르는 중** + **가격 자체도 오르는 중**
    - 하락: 종가가 이동평균 **아래** + 이동평균이 **내리는 중** + **가격 자체도 내리는 중**
    - 횡보: 그 외 (셋 중 하나라도 엇갈리는 구간)

    위치만 보지 않고 기울기를 함께 보는 이유는, 이동평균을 막 뚫은 직후처럼 방향이
    확정되지 않은 구간을 상승/하락으로 단정하지 않기 위해서다.

    **가격 조건(`price_days`)을 추가한 이유** (2026-09-22):
    이동평균 기울기는 가격보다 늦게 돈다. 급락이 50일 창에 남아 있는 동안 가격이 이미
    평평해져도 선은 계속 내려가므로, 실제로는 횡보인 구간이 "하락"으로 분류됐다.
    2026-08-03~09-17이 그 예다 — SOXX가 507→511로 평평했는데 35일 중 25일이 하락이었다.
    16.3년 전체로도 "하락" 라벨 44구간 중 **48%가 오르면서 끝났고** 구간 수익률 중앙값이
    -0.17%로 사실상 0이었다. 라벨이 실제 방향을 잡아내지 못한 것이다.

    해결책으로 **MA 기간을 줄이는 방식은 실패했다.** 15~30일로 줄이면 8~9월은 횡보로
    잡히지만 레짐 전환이 341회→671~761회로 두 배가 되어 휩쏘 비용이 이득을 삼킨다
    (전체 기간 0.27~18.94배). 대신 MA는 50일로 두고 **가격의 20일 변화**를 조건에
    더하면 전환 빈도를 늘리지 않으면서(341→...) 라벨이 실제 방향에 맞는다.
    docs/STRATEGY.md 3.1 참고.
    """
    ma = close.rolling(ma_period).mean()
    slope = ma.diff(slope_days)
    price_chg = close.diff(price_days)
    regime = pd.Series(SIDEWAYS, index=close.index, dtype=object)
    regime[(close > ma) & (slope > 0) & (price_chg > 0)] = UP
    regime[(close < ma) & (slope < 0) & (price_chg < 0)] = DOWN
    # 워밍업 구간은 거래하지 않는다
    regime[ma.isna() | slope.isna() | price_chg.isna()] = None
    return regime
